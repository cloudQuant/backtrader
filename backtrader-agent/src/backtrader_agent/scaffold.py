def _strategy_source(spec: StrategySpec) -> str:
    init_body, next_body = ARCHETYPE_CODE[spec.archetype]
    fast = int(spec.parameter_defaults.get("fast_period", 5))
    slow = int(spec.parameter_defaults.get("slow_period", 12))
    return f'''"""Generated by backtrader-agent from StrategySpec {spec.spec_hash}."""
import backtrader as bt


class GeneratedStrategy(bt.Strategy):
    params = (
        ("fast_period", {fast}),
        ("slow_period", {slow}),
    )

    def __init__(self):
{init_body}
        self._agent_buy_count = 0
        self._agent_sell_count = 0

    def next(self):
{next_body}

    def notify_order(self, order):
        if order.status == order.Completed:
            if order.isbuy():
                self._agent_buy_count += 1
            elif order.issell():
                self._agent_sell_count += 1
'''


def _pandas_custom_feed_source(dataset: Dict[str, Any]) -> str:
    classes = []
    branches = []
    for index, feed in enumerate(dataset.get("feeds", [])):
        if feed.get("format") != "pandas_custom_lines":
            continue
        canonical_columns = list(feed.get("canonical_columns", []))
        custom_lines = tuple(canonical_columns[7:])
        class_name = f"AgentPandasData{index}"
        parameters = tuple((line_name, line_name) for line_name in custom_lines)
        if custom_lines:
            classes.append(
                f"class {class_name}(bt.feeds.PandasData):\n"
                f"    lines = {custom_lines!r}\n"
                f"    params = {parameters!r}\n"
            )
        else:
            class_name = "bt.feeds.PandasData"
        branches.append(f'    if feed_name == {feed["name"]!r}:\n' f"        return {class_name}\n")
    body = "\n\n".join(classes)
    if body:
        body += "\n\n"
    return (
        body
        + "def _pandas_custom_feed_class(feed_name):\n"
        + "".join(branches)
        + '    raise RuntimeError("custom Pandas feed was not rendered for this dataset")\n'
    )



class CanonicalBacktraderCSVData(bt.feeds.BacktraderCSVData):
    """Load canonical CAS rows through Backtrader's fixed CSV parser."""

    def _loadline(self, tokens):
        native = list(tokens[:7])
        native[0] = native[0][:10]
        return super()._loadline(native)


class CanonicalYahooCSVData(bt.feeds.YahooFinanceCSVData):
    """Adapt canonical CAS rows to the offline Yahoo parser contract."""

    def _loadline(self, tokens):
        native = [
            tokens[0][:10],
            tokens[1],
            tokens[2],
            tokens[3],
            tokens[4],
            tokens[4],
            tokens[5],
        ]
        return super()._loadline(native)



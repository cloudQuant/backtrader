def _run_composite_indicator(indicator_class, runonce):
    """Run one real indicator against a small in-memory OHLC series."""
    frame = pd.DataFrame(
        {
            "open": [10.0, 11.0, 12.0, 11.0, 13.0, 12.0, 14.0, 15.0, 14.0, 16.0, 17.0, 16.0],
            "high": [11.0, 12.0, 13.0, 12.0, 14.0, 13.0, 15.0, 16.0, 15.0, 17.0, 18.0, 17.0],
            "low": [9.0, 10.0, 11.0, 10.0, 12.0, 11.0, 13.0, 14.0, 13.0, 15.0, 16.0, 15.0],
            "close": [10.0, 11.0, 12.0, 11.0, 13.0, 12.0, 14.0, 15.0, 14.0, 16.0, 17.0, 16.0],
            "volume": [1.0] * 12,
            "openinterest": [0.0] * 12,
        },
        index=pd.date_range("2020-01-01", periods=12, freq="D"),
    )
    result = {}

    class CompositeProbeStrategy(bt.Strategy):
        def __init__(self):
            self.indicator = indicator_class(self.data, period=3)

        def stop(self):
            line_names = tuple(self.indicator.lines.getlinealiases())
            result["line_names"] = line_names
            result["indexes_match"] = all(
                getattr(self.indicator.lines, name) is self.indicator.lines[index]
                for index, name in enumerate(line_names)
            )
            result["series"] = {
                name: tuple(getattr(self.indicator.lines, name).array)
                for name in line_names
            }

    cerebro = bt.Cerebro(stdstats=False)
    cerebro.adddata(bt.feeds.PandasData(dataname=frame))
    cerebro.addstrategy(CompositeProbeStrategy)
    cerebro.run(runonce=runonce, preload=True)
    return result


def test_envelope_and_directional_composites_construct_in_both_run_modes():
    cases = (
        (btind.Envelope, ("src", "top", "bot"), ("src",)),
        (btind.SMAEnvelope, ("sma", "top", "bot"), ("sma",)),
        (
            btind.DirectionalMovementIndex,
            ("adx", "plusDI", "minusDI"),
            ("adx", "plusDI", "minusDI"),
        ),
        (
            btind.DirectionalMovement,
            ("adx", "adxr", "plusDI", "minusDI"),
            ("adx", "adxr", "plusDI", "minusDI"),
        ),
    )

    for indicator_class, expected_names, calculated_names in cases:
        runnext = _run_composite_indicator(indicator_class, runonce=False)
        runonce = _run_composite_indicator(indicator_class, runonce=True)
        assert runnext["line_names"] == runonce["line_names"] == expected_names
        assert runnext["indexes_match"] is True
        assert runonce["indexes_match"] is True

        for line_name in expected_names:
            next_values = runnext["series"][line_name]
            once_values = runonce["series"][line_name]
            assert len(next_values) == len(once_values) == 12

        for line_name in calculated_names:
            next_values = runnext["series"][line_name]
            once_values = runonce["series"][line_name]
            assert once_values[-1] == pytest.approx(next_values[-1])

        # The envelope source/average and all directional outputs are
        # calculated by their current implementations.  The band-value
        # calculation is outside this line-container fix.
        for line_name in calculated_names:
            assert math.isfinite(runnext["series"][line_name][-1])
            assert math.isfinite(runonce["series"][line_name][-1])
